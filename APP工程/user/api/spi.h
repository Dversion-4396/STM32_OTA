/*=====================================================================
 * 文件：spi.h
 * 说明：SPI2 + W25Q128 外部 Flash 驱动
 * 负责：D
 *
 * 硬件连接（战神V1）：
 *   CS   = PB12    ★PB12 不能当普通 IO，悬空会让 SPI2 报废★
 *   SCK  = PB13
 *   MISO = PB14
 *   MOSI = PB15
 *
 * W25Q128 参数：16MB，页 256B，扇区 4KB，块 64KB，JEDEC ID = 0xEF4018
 *====================================================================*/
#ifndef __SPI_H
#define __SPI_H

#include "common.h"

/*==================== 引脚定义 ====================*/
#define W25Q_CS_PORT        GPIOB
#define W25Q_CS_PIN         GPIO_Pin_12

#define W25Q_CS_LOW()       (W25Q_CS_PORT->BRR  = W25Q_CS_PIN)
#define W25Q_CS_HIGH()      (W25Q_CS_PORT->BSRR = W25Q_CS_PIN)

/*==================== W25Q128 指令 ====================*/
#define W25Q_JEDEC_ID       0x9F
#define W25Q_READ_STATUS    0x05
#define W25Q_WRITE_ENABLE   0x06
#define W25Q_READ_DATA      0x03
#define W25Q_PAGE_PROGRAM   0x02
#define W25Q_SECTOR_ERASE   0x20
#define W25Q_BLOCK_ERASE    0xD8

#define W25Q128_JEDEC_ID    0xEF4018

/*==================== 函数声明 ====================*/

/*---------------------------------------------------------------------
 * 函数：SPI2_Init
 * 功能：初始化 SPI2（PB12/13/14/15）
 * 参数：无
 * 返回：无
 * 负责：D
 *-------------------------------------------------------------------*/
void SPI2_Init(void);

/*---------------------------------------------------------------------
 * 函数：SPI2_ReadWriteByte
 * 功能：SPI2 全双工收发一个字节
 * 参数：data - 要发送的字节
 * 返回：收到的字节
 * 负责：D
 *-------------------------------------------------------------------*/
u8 SPI2_ReadWriteByte(u8 data);

/*---------------------------------------------------------------------
 * 函数：W25Q128_ReadID
 * 功能：读 JEDEC ID
 * 参数：无
 * 返回：24 位 ID（Winbond 128Mbit = 0xEF4018）
 * 负责：D
 *-------------------------------------------------------------------*/
u32 W25Q128_ReadID(void);

/*---------------------------------------------------------------------
 * 函数：W25Q128_Init
 * 功能：初始化并检查 ID
 * 参数：无
 * 返回：0=成功  1=ID 不对
 * 负责：D
 *-------------------------------------------------------------------*/
u8 W25Q128_Init(void);

/*---------------------------------------------------------------------
 * 函数：W25Q128_WaitBusy
 * 功能：等待芯片空闲
 * 参数：无
 * 返回：无
 * 负责：D
 * 说明：★擦除/写入后必须调用★
 *-------------------------------------------------------------------*/
void W25Q128_WaitBusy(void);

/*---------------------------------------------------------------------
 * 函数：W25Q128_WriteEnable
 * 功能：写使能
 * 参数：无
 * 返回：无
 * 负责：D
 * 说明：★每次擦除/写入前必须调用，不发就写不进去★
 *-------------------------------------------------------------------*/
void W25Q128_WriteEnable(void);

/*---------------------------------------------------------------------
 * 函数：W25Q128_EraseSector
 * 功能：擦除一个扇区（4KB）
 * 参数：sector - 扇区号（0~4095）
 * 返回：无
 * 负责：D
 *-------------------------------------------------------------------*/
void W25Q128_EraseSector(u16 sector);

/*---------------------------------------------------------------------
 * 函数：W25Q128_EraseBlock
 * 功能：擦除一个块（64KB）
 * 参数：block - 块号（0~255）
 * 返回：无
 * 负责：D
 * 说明：OTA 下载前用这个擦第 0 块
 *-------------------------------------------------------------------*/
void W25Q128_EraseBlock(u8 block);

/*---------------------------------------------------------------------
 * 函数：W25Q128_WritePage
 * 功能：写一页（256B，不跨页）
 * 参数：page - 页号（0~65535）；buf - 数据（至少 256 字节）
 * 返回：无
 * 负责：D
 * 说明：★调用前必须确保该页已擦除★
 *-------------------------------------------------------------------*/
void W25Q128_WritePage(u16 page, u8 *buf);

/*---------------------------------------------------------------------
 * 函数：W25Q128_Read
 * 功能：读数据
 * 参数：addr - 起始地址；buf - 缓冲区；len - 长度
 * 返回：无
 * 负责：D
 *-------------------------------------------------------------------*/
void W25Q128_Read(u32 addr, u8 *buf, u32 len);

/*---------------------------------------------------------------------
 * 函数：W25Q128_Write
 * 功能：写数据（自动处理跨页）
 * 参数：addr - 起始地址；buf - 数据；len - 长度
 * 返回：0=成功
 * 负责：D
 * 说明：★调用前必须已擦除目标区域★
 *       ★跨扇区时不能每写一段就擦，会擦掉已写数据★
 *-------------------------------------------------------------------*/
u8 W25Q128_Write(u32 addr, u8 *buf, u32 len);

/*---------------------------------------------------------------------
 * 函数：W25Q128_SelfTest
 * 功能：自测（读ID + 擦除 + 写入 + 读回比对）
 * 参数：无
 * 返回：0=全部通过  1=ID错  2=擦除失败  3=读回不一致
 * 负责：D
 *-------------------------------------------------------------------*/
u8 W25Q128_SelfTest(void);

#endif /* __SPI_H */
