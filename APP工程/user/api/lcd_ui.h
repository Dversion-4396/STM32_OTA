#ifndef _LCD_UI_H
#define _LCD_UI_H

#include "common.h"

/*
	LCD 界面层 —— 手机式布局（2.4 寸 ST7789V，240x320）
	==================================================================
	屏幕: 240 x 320 竖屏, ST7789V, 65K 色(RGB565), 16 号字(8x16 像素)
	      每行可放 30 个字符（240 / 8），共 20 行（320 / 16）。

	布局（纵向铺满 320，末尾留 12px）:
	┌──────────────────────────────┐
	│STM32 OTA              ▁▃▅█  │ y=  0  状态栏 24px（深蓝底白字 + 右上信号格）
	├──────────────────────────────┤ y= 24  分隔线 2px
	│APP  OTA                      │ y= 26  当前运行的 APP
	├──────────────────────────────┤ y= 42  分隔线 2px
	│                              │
	│       [ 大肥鱼图片 ]         │ y= 44  图片区 92px（240x92，16 色）
	│                              │
	├──────────────────────────────┤ y=136  分隔线 4px
	│UP:123s                       │ y=140  运行时长
	│4G:OK FLSH:OK EEP:OK          │ y=156  外设状态
	│MQTT:OK RX:42                 │ y=172  云连接 + 收包数
	│EV:20000000                   │ y=188  事件标志（十六进制）
	├──────────────────────────────┤ y=204  分隔线 4px
	│> OTA                         │ y=208  APP 列表第 1 行（选中=蓝底白字）
	│  APP2                        │ y=224  APP 列表第 2 行
	│  APP3                        │ y=240  APP 列表第 3 行
	├──────────────────────────────┤ y=256  分隔线 4px
	│>最新一条日志                 │ y=260  日志区第 1 行
	│>上一条日志                   │ y=276  日志区第 2 行
	│>再上一条                     │ y=292  日志区第 3 行
	└──────────────────────────────┘ y=308  余 12px 留白

	★ 状态栏右上角信号格（4 格，越高越亮）:
	    都没连上        → 4 格全灭（暗灰）
	    4G 上网成功     → 亮 3 格
	    MQTT 连上巴法云 → 亮 4 格（全绿）
	    OTA 下载中      → 4 格闪红
	  这样一眼就能看出"卡在哪一步"：全灭=没网，3格=有网没连云，4格=全通。

	★ 图片区:
	  一张 240x92 的 16 色图片（数据在 lcd_img.h，由 tools\img2lcd.py 生成）。
	  开机画一次，之后主循环完全不碰这块。
	  ★ 为什么是 4bpp：MDK-ARM Lite 卡 32KB 镜像，RGB565 的 53760 字节装不下。

	★ 刷新策略（关键, 避免拖慢主循环）:
	  全屏填充 240x320 = 76800 像素 = 153600 次 SPI 写, 实测约 560ms。
	  所以:
	    1. 开机只做一次全屏清 + 画静态框架（这一次慢无所谓）
	    2. 图片区只在开机画一次，主循环里零开销
	    3. 运行信息/APP 名/列表每约 500ms 检查一次, 内容没变就一个字节都不发
	    4. 日志一来就立刻刷（不等 500ms），否则缓冲区会覆盖掉用户还没看到的内容
*/

#define UI_APP_MAX      3           /* 列表区最多显示几行 */
#define UI_FONT_H       16
#define UI_FONT_W       8

#define UI_COLS         30          /* 每行字符数 = 240 / 8 */
#define UI_LOG_LINES    3           /* 日志区行数（2026-11-02 图片高度从112缩到92，腾出20px给日志加一行） */
#define UI_LOG_COLS     29          /* 日志正文列数（前面留 1 列画 ">"） */

/*---------- 各区域 y 坐标（改这里就能整体调整布局）----------
   纵向核算（屏高 320）：
     状态栏      0 .. 23   (24)
     分隔线1    24 .. 25   (2)
     APP 名     26 .. 41   (16)
     分隔线2    42 .. 43   (2)
     图片区     44 .. 135  (92)
     分隔线3   136 .. 139  (4)
     运行信息  140 .. 203  (4 行 x 16)
     分隔线4   204 .. 207  (4)
     APP 列表  208 .. 255  (3 行 x 16)
     分隔线5   256 .. 259  (4)
     日志      260 .. 307  (3 行 x 16)
     末尾剩余  308 .. 319  (12)
   ----------------------------------------------------------*/
#define UI_Y_STAT       0
#define UI_STAT_H       24          /* 状态栏高度（比字体高，显得像个手机状态栏） */
#define UI_Y_SEP1       24
#define UI_Y_APPNAME    26
#define UI_Y_SEP2       42
#define UI_Y_ANIM       44
#define UI_ANIM_H       92          /* 图片高度，必须和 lcd_img.h 的 LCD_IMG_H 一致 */
#define UI_Y_SEP3       136
#define UI_Y_INFO       140         /* 运行信息 4 行 */
#define UI_Y_SEP4       204
#define UI_Y_LIST       208
#define UI_ROW_STEP     16
#define UI_Y_SEP5       256
#define UI_Y_LOG        260         /* 日志区 3 行 */
#define UI_LOG_STEP     16

/* ============================================================
   运行状态 —— 由 main.c 在初始化各步骤后设置
   ============================================================ */
typedef struct
{
    u8  gprs_ok;      /* 4G 激活上网成功 = 1 */
    u8  flash_ok;     /* W25Q128 初始化成功 = 1 */
    u8  eeprom_ok;    /* EEPROM 参数有效 = 1 */
    u8  mqtt_ok;      /* MQTT 已连上巴法云 = 1 */
    u8  ota_busy;     /* OTA 下载中 = 1 */
    u32 rx_pkts;      /* 收到的 MQTT 报文数 */
} UI_Status;

extern UI_Status g_ui_status;

/*
	初始化界面: 清屏 + 画静态框架。在 LCD_Init() 之后调用一次。
	★ 全屏清屏约 560ms, 只在开机做这一次。
*/
void LCD_UI_Init(void);

/*
	主循环里每轮调用一次, 内部自带节流。
	返回: 1 = 本次有更新 / 0 = 没到时间或没变化
*/
u8 LCD_UI_Update(void);

/* 强制全量刷新（忽略缓存, 调试用） */
void LCD_UI_Refresh_All(void);

/* ============================================================
   APP 列表
   ============================================================ */
void LCD_UI_SetAppCount(u8 count);                /* 列表里有几个 APP（最多 3） */
void LCD_UI_SetAppName(u8 idx, const char *name); /* 设置第 idx 个 APP 的名字 */
void LCD_UI_SetCurrentApp(u8 idx);                /* 当前运行第几个 */
u8   LCD_UI_GetCurrentApp(void);
void LCD_UI_NextApp(void);                        /* 切到下一个（以后接按键用） */

/*
	往屏幕日志区追加一条日志（屏幕底部 2 行，最新在下）。
	★ 只接受 ASCII 0x20~0x7E，中文会被替换成 '.'（字模表只有 ASCII）。
	★ 每条自动截断到 UI_LOG_COLS 个字符。
	★ 调用后立刻刷屏，不等 500ms 节拍。
*/
void LCD_Log(const char *s);

#endif
