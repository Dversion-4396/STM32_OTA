#ifndef _LCD_UI_H
#define _LCD_UI_H

#include "common.h"

/*
	LCD 界面层 —— 运行信息 + 日志
	==================================================================
	屏幕: 128 x 160 竖屏, ST7735S, 16 号字（每字符 8x16 像素, 一行 16 个字符）

	布局（严格按像素算过, 合计 146 像素 <= 160）:
	┌────────────────────────┐
	│STM32 OTA v1.0          │ y=  0  标题栏（蓝底白字, 开机画一次）
	│UP:123s                 │ y= 16  运行时长（秒）
	│4G:OK FLSH:OK           │ y= 32  外设状态
	│MQTT:OK EEP:OK          │ y= 48  云端连接 / EEPROM 参数
	│EV:20000000             │ y= 64  事件标志（十六进制, 看状态机在哪一步）
	│▀▀▀▀▀▀▀▀▀▀▀▀▀▀▀▀        │ y= 80  分隔线（2px 灰条, 不用画线函数）
	│[LOG]                   │ y= 82  日志区标题
	│>1.配置APN              │ y= 98  日志行 1
	│>2.开网络               │ y=114  日志行 2
	│>CIPOPEN OK             │ y=130  日志行 3
	└────────────────────────┘ y=146 起空余 14 像素

	★ 为什么日志只有 3 行:
	    5 行信息  5x16 = 80  (y=0..79)
	    分隔线         2     (y=80..81)
	    日志标题  1x16 = 16  (y=82..97)
	    日志正文  3x16 = 48  (y=98..145)
	    合计          146    <= 160  ✅
	  硬塞 4 行: 80+2+16+64 = 162 > 160, 最后一行被切掉 2 像素。

	★ 刷新策略（关键, 避免拖慢主循环）:
	  全屏填充 128x160 = 40960 次 SPI 字节写, 实测约 150ms。
	  如果每轮主循环都全屏重绘, 10ms 的循环周期直接变成 160ms,
	  MQTT 心跳和串口接收全都会受影响。
	  所以:
	    1. 开机只做一次全屏清屏 + 画静态标题栏/分隔线
	    2. 之后只重绘【内容有变化的行】, 且每行重绘前先 LCD_Fill 清掉旧内容
	    3. 用缓存记录上次显示的内容, 没变就一个字节都不发
	    4. 整体约 500ms 节流（人眼够用, 开销可忽略）
*/

/* ============================================================
   运行状态 —— 由 main.c 在初始化各步骤后设置
   ============================================================ */
typedef struct
{
    u8  gprs_ok;      /* 4G 激活成功 = 1 */
    u8  flash_ok;     /* W25Q128 初始化成功 = 1 */
    u8  eeprom_ok;    /* EEPROM 参数有效 = 1 */
    u8  mqtt_ok;      /* MQTT 已连上 = 1 */
    u8  ota_busy;     /* OTA 下载中 = 1 */
    u32 rx_pkts;      /* 收到的 MQTT 报文数（用于看通信是否活） */
} UI_Status;

extern UI_Status g_ui_status;

/*
	初始化界面: 清屏 + 画静态标题栏 + 分隔线。在 LCD_Init() 之后调用一次。
	★ 全屏清屏约 150ms, 只在开机做这一次。
*/
void LCD_UI_Init(void);

/*
	主循环里每轮调用一次, 内部自带节流（约 500ms 刷一次）。
	返回: 1 = 本次有更新 / 0 = 没到时间或没变化
*/
u8 LCD_UI_Update(void);

/*
	往屏幕日志区追加一行。
	★ 会被截断到 15 个字符（">" + 15 字 = 16 字 = 128 像素, 正好铺满）。
	★ 只接受 ASCII（0x20~0x7E）—— 字模表只覆盖这一段。
	  中文会被替换成 '.'（不是空格 —— 空格会让人以为"这里本来就空"）。
	  所以日志内容请用英文/数字, 比如 "GPRS OK" 而不是 "4G 激活成功"。
	★ 会自动去掉结尾的 \r \n 和开头的 '>'。
*/
void LCD_Log(const char *s);

/* 强制全量刷新（忽略缓存, 调试用） */
void LCD_UI_Refresh_All(void);

#endif
