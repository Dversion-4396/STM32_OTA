/*=====================================================================
 * 文件：boot.h
 * 说明：BootLoader 主逻辑
 * 负责：B
 *
 * BootLoader 要做的 5 件事：
 *   ① Flash 擦写（见 stmflash.c）
 *   ② 串口救砖菜单
 *   ③ EEPROM 读写（存三元组和 OTA 标志）
 *   ④ 从 W25Q128 搬固件到 A 区
 *   ⑤ 跳转到 APP
 *====================================================================*/
#ifndef __BOOT_H
#define __BOOT_H

#include "common.h"

/*==================== 事件标志 ====================*/
#define A_XMODEM       0x00000001      /* A 区下载（Xmodem）事件 */
#define ALIYUN_CER     0x00000002      /* 设置三元组事件 */
#define OTA_MODEM      0x00000004      /* A 区下载（OTA）事件 */

extern u32 BootEventFlag;

/*---------------------------------------------------------------------
 * 函数：BootLoader_Branch
 * 功能：分支判断（三种走向）
 * 参数：无
 * 返回：无
 * 负责：B
 *
 * 判断逻辑：
 *   1. 等 2 秒，收到 'w' → 进菜单（返回）
 *   2. EEPROM 里 OTA_flag == BOOT_STA_O → 置 OTA_MODEM 事件（返回）
 *   3. 其他 → Load_APP(FLASH_A_ADDR)
 *-------------------------------------------------------------------*/
void BootLoader_Branch(void);

/*---------------------------------------------------------------------
 * 函数：BootLoader_Info
 * 功能：打印菜单
 * 参数：无
 * 返回：无
 * 负责：B
 *-------------------------------------------------------------------*/
void BootLoader_Info(void);

/*---------------------------------------------------------------------
 * 函数：BootLoader_Event
 * 功能：处理串口命令
 * 参数：data - 数据；len - 长度
 * 返回：无
 * 负责：B
 *-------------------------------------------------------------------*/
void BootLoader_Event(u8 *data, u16 len);

/*---------------------------------------------------------------------
 * 函数：ActiveEvent
 * 功能：主动事件（处理 OTA 搬移）
 * 参数：无
 * 返回：无
 * 负责：B
 *-------------------------------------------------------------------*/
void ActiveEvent(void);

/*---------------------------------------------------------------------
 * 函数：Load_APP
 * 功能：跳转到 APP
 * 参数：app_addr - APP 起始地址（0x08008000）
 * 返回：无（成功就不返回）
 * 负责：B
 *
 * ★最容易出错的地方，6 个步骤一个不能少★
 *-------------------------------------------------------------------*/
void Load_APP(u32 app_addr);

/*---------------------------------------------------------------------
 * 函数：Boot_VerifyFirmware
 * 功能：校验 W25Q128 里的固件（28 字节尾缀 + MD5）
 * 参数：fw_total_len - 总长度（含尾缀）
 *       out_real_len - 输出：真实长度（不含尾缀）
 * 返回：0=通过
 * 负责：B（加分项，时间紧可以跳过）
 *-------------------------------------------------------------------*/
u8 Boot_VerifyFirmware(u32 fw_total_len, u32 *out_real_len);

/*---------------------------------------------------------------------
 * 函数：Boot_CopyFirmware
 * 功能：从 W25Q128 搬移固件到 A 区
 * 参数：fw_len - 固件长度（不含尾缀）
 * 返回：0=成功
 * 负责：B
 *-------------------------------------------------------------------*/
u8 Boot_CopyFirmware(u32 fw_len);

/* 升级执行函数：校验 + 擦除 + 搬运 + 写回版本信息，一步到位
 * 菜单 [4] 和 ActiveEvent() 都调它，保证两条路行为完全一致
 * 返回：0 = 成功  1 = 校验失败  2 = 擦除失败  3 = 搬运失败 */
u8 Boot_DoUpgrade(u32 new_len, u32 new_ver_num, const char *new_ver);

/*=====================================================================
 * 备份 / 回退（2026-11-04 新增）
 *
 * 存储布局（W25Q128）：
 *   0x000000 ~ 0x07FFFF  OTA 下载暂存区（APP 擦 block 0~7）
 *   0x080000             备份头（32 字节，占一个 4KB 扇区）
 *   0x081000 起          备份镜像
 *=====================================================================*/
/* 读备份头。返回 0 = 有效；1 = 没有备份；2 = 头内容非法 */
u8 Boot_BakReadHdr(u32 *img_len, u32 *ver_num, u32 *sum, char *ver);

/* 把当前 A 区备份进 W25Q128。返回 0 = 成功
 * ★由 Boot_DoUpgrade 在擦除 A 区之前自动调用★ */
u8 Boot_BackupCurrent(void);

/* 打印备份信息（菜单 [5]） */
void Boot_BakShow(void);

/* 把备份搬回 A 区（菜单 [6]）。返回 0 = 成功
 *   1 = 没有备份  2 = 校验和不符  3 = 向量表非法  4 = 擦除失败  5 = 写入失败 */
u8 Boot_Rollback(void);

/*---------------------------------------------------------------------
 * 函数：EEPROM_ReadInfo
 * 功能：从 EEPROM 读取三元组和 OTA 标志
 * 参数：无
 * 返回：0 = 参数有效，1 = 参数无效（首次上电 / 未配置 / 数据损坏）
 * 负责：B
 *-------------------------------------------------------------------*/
u8 EEPROM_ReadInfo(void);

/*---------------------------------------------------------------------
 * 函数：EEPROM_SaveInfo
 * 功能：保存三元组和 OTA 标志到 EEPROM
 * 参数：无
 * 返回：0=成功
 * 负责：B
 * 说明：★AT24C02 每写一字节要 delay_ms(5)★
 *-------------------------------------------------------------------*/
u8 EEPROM_SaveInfo(void);

/*---------------------------------------------------------------------
 * 函数：AliCer_Inspect
 * 功能：校验并解析三元组
 * 参数：data - 字符串，格式 /pk/dn/ds/version/
 * 返回：0=成功  1~4=字段长度错  5=格式错
 * 负责：B
 *
 * ★长度硬校验★：
 *   ProductKey 必须正好 11
 *   DeviceName ≤ 32
 *   DeviceSecret 必须正好 32
 *   版本号 必须正好 23
 *-------------------------------------------------------------------*/
u8 AliCer_Inspect(u8 *data);

/*---------------------------------------------------------------------
 * 函数：Printf_AliCer
 * 功能：打印当前三元组
 * 参数：无
 * 返回：无
 * 负责：B
 *-------------------------------------------------------------------*/
void Printf_AliCer(void);

#endif /* __BOOT_H */
