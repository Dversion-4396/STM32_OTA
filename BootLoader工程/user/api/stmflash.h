/*=====================================================================
 * 文件：stmflash.h
 * 说明：STM32F103 内部 Flash 读写驱动
 * 负责：B
 *
 * ★核心难点：F103 是「2 字节半字」编程，不是 G0 的 8 字节双字★
 *   G0:   HAL_FLASH_Program(FLASH_TYPEPROGRAM_DOUBLEWORD, addr, data)
 *   F103: FLASH_ProgramHalfWord(addr, data)
 *====================================================================*/
#ifndef __STMFLASH_H
#define __STMFLASH_H

#include "common.h"

/*---------------------------------------------------------------------
 * 函数：Flash_ErasePage
 * 功能：擦除一页（2KB）
 * 参数：addr - 页起始地址（必须 2KB 对齐）
 * 返回：0=成功  1=地址未对齐  2=擦除失败
 * 负责：B
 *-------------------------------------------------------------------*/
u8 Flash_ErasePage(u32 addr);

/*---------------------------------------------------------------------
 * 函数：Flash_EraseApp
 * 功能：擦除整个 A 区（240 页 = 480KB）
 * 参数：无
 * 返回：0=成功  1=失败
 * 负责：B
 * 说明：搬移固件前必须先调用
 *-------------------------------------------------------------------*/
u8 Flash_EraseApp(void);

/*---------------------------------------------------------------------
 * 函数：Flash_Write
 * 功能：写 Flash（自动按半字拆分）
 * 参数：addr - 目标地址（必须 2 字节对齐）
 *       buf  - 数据
 *       len  - 字节数（必须为偶数）
 * 返回：0=成功  1=地址未对齐  2=长度非偶数  3=写失败
 * 负责：B
 *
 * ★小端拼装：halfword = buf[i] | (buf[i+1] << 8)★
 *-------------------------------------------------------------------*/
u8 Flash_Write(u32 addr, u8 *buf, u32 len);

/*---------------------------------------------------------------------
 * 函数：Flash_Read
 * 功能：读 Flash
 * 参数：addr - 地址；buf - 缓冲区；len - 长度
 * 返回：无
 * 负责：B
 * 说明：Flash 可以直接当内存读，用 memcpy 即可
 *-------------------------------------------------------------------*/
void Flash_Read(u32 addr, u8 *buf, u32 len);

/*---------------------------------------------------------------------
 * 函数：Flash_IsBlank
 * 功能：判断是否为空（全 FF）
 * 参数：addr - 地址；len - 长度
 * 返回：1=全FF  0=有数据
 * 负责：B
 *-------------------------------------------------------------------*/
u8 Flash_IsBlank(u32 addr, u32 len);

/*---------------------------------------------------------------------
 * 函数：Flash_SelfTest
 * 功能：自测（擦除 + 写入 + 读回比对）
 * 参数：无
 * 返回：0=全部通过
 * 负责：B
 *
 * ★测试地址必须用 A 区（0x08008000），不能用 0x08000000★
 *   否则会把 BootLoader 自己擦了
 *-------------------------------------------------------------------*/
u8 Flash_SelfTest(void);

#endif /* __STMFLASH_H */
